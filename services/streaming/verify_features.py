#!/usr/bin/env python3
"""
Urbanix — Day 3 Feature Table Verification Script
Inspects, validates, and reports on Parquet feature tables generated by
the Day 3 Spark Structured Streaming pipelines:
  - data/feature_table/traffic/
  - data/feature_table/aqi/
  - data/feature_table/weather/

Verification Capabilities:
1. Directory Existence & Emptiness:
   Distinguishes missing directories, empty directories, and populated Parquet datasets.
2. Schema & Metadata Validation:
   Checks expected columns, window definitions, and enriched static zone metadata.
3. 5-Minute Window Boundary Validation:
   Asserts (window_end - window_start) == 300 seconds (5 minutes) and window alignment.
4. Key Uniqueness:
   Verifies that (window_start, zone_id) is unique within each independent feature dataset.
5. Measurement Integrity:
   Verifies presence of valid sensor aggregates without synthetic fields (e.g. no vehicle_count, no co2).
6. Honest Diagnostic Reporting:
   Exits with status 0 only if all assertions pass on non-empty datasets, or non-zero with explicit error report.
"""

import os
import sys
import argparse
import logging
from typing import Dict, Any, List, Optional

# Ensure worker python matches driver python runtime
os.environ.setdefault("PYSPARK_PYTHON", sys.executable)
os.environ.setdefault("PYSPARK_DRIVER_PYTHON", sys.executable)

try:
    from pyspark.sql import SparkSession
    from pyspark.sql.functions import col, unix_timestamp
except ImportError:
    SparkSession = None

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] [Urbanix-Verifier] %(message)s",
)
logger = logging.getLogger("UrbanixVerifier")


EXPECTED_SCHEMAS = {
    "traffic": {
        "required_cols": [
            "window_start",
            "window_end",
            "zone_id",
            "traffic_record_count",
            "avg_speed_kmph",
            "min_speed_kmph",
            "max_speed_kmph",
            "zone_name",
        ],
        "prohibited_cols": ["vehicle_count", "co2"],
    },
    "aqi": {
        "required_cols": [
            "window_start",
            "window_end",
            "zone_id",
            "aqi_record_count",
            "avg_pm25",
            "min_pm25",
            "max_pm25",
            "zone_name",
        ],
        "prohibited_cols": ["co2", "vehicle_count"],
    },
    "weather": {
        "required_cols": [
            "window_start",
            "window_end",
            "zone_id",
            "weather_record_count",
            "avg_temperature_c",
            "min_temperature_c",
            "max_temperature_c",
            "avg_humidity_pct",
            "zone_name",
        ],
        "prohibited_cols": ["co2", "vehicle_count"],
    },
}


def check_directory(dir_path: str) -> Dict[str, Any]:
    """
    Checks existence and parquet file content of a directory.
    """
    if not os.path.exists(dir_path):
        return {"exists": False, "empty": True, "parquet_files": 0}

    parquet_files = [
        f for f in os.listdir(dir_path) if f.endswith(".parquet") and not f.startswith(".")
    ]
    is_empty = len(parquet_files) == 0
    return {"exists": True, "empty": is_empty, "parquet_files": len(parquet_files)}


def verify_dataset(
    spark: SparkSession,
    stream_name: str,
    dir_path: str,
    rules: Dict[str, Any],
) -> bool:
    """
    Loads and validates a single stream feature dataset.
    Returns True if all checks pass, False otherwise.
    """
    print("\n" + "=" * 70)
    print(f"VERIFYING FEATURE DATASET: {stream_name.upper()} ({dir_path})")
    print("=" * 70)

    dir_status = check_directory(dir_path)
    if not dir_status["exists"]:
        logger.error(f"Directory DOES NOT EXIST: {dir_path}")
        return False

    if dir_status["empty"]:
        logger.error(
            f"Directory exists but is EMPTY (0 parquet part files found in {dir_path})."
        )
        logger.info(
            "Remediation: Confirm that Kafka producer published events and that the "
            "watermark advanced sufficiently for tumbling window closure."
        )
        return False

    logger.info(f"Found {dir_status['parquet_files']} Parquet data file(s). Loading into Spark...")

    try:
        df = spark.read.parquet(dir_path)
    except Exception as e:
        logger.error(f"Failed to read Parquet data from {dir_path}: {e}")
        return False

    total_rows = df.count()
    print(f"[*] Total rows recorded: {total_rows}")

    if total_rows == 0:
        logger.error(f"Dataset in {dir_path} contains 0 rows.")
        return False

    print("\n--- Schema ---")
    df.printSchema()

    actual_cols = df.columns
    print(f"[*] Actual columns: {actual_cols}")

    # Check required columns
    missing_cols = [c for c in rules["required_cols"] if c not in actual_cols]
    if missing_cols:
        logger.error(f"Missing required columns in {stream_name}: {missing_cols}")
        return False

    # Check prohibited columns
    fabricated_cols = [c for c in rules.get("prohibited_cols", []) if c in actual_cols]
    if fabricated_cols:
        logger.error(f"Prohibited/fabricated columns detected in {stream_name}: {fabricated_cols}")
        return False

    print("\n--- Sample Records (First 5) ---")
    df.show(5, truncate=False)

    # 1. Zone distribution
    distinct_zones = [r["zone_id"] for r in df.select("zone_id").distinct().collect()]
    print(f"[*] Distinct zones represented ({len(distinct_zones)}): {distinct_zones}")

    # 2. Window boundary validation (must be exactly 5 minutes = 300 seconds)
    df_window_sec = df.withColumn(
        "window_duration_sec",
        unix_timestamp("window_end") - unix_timestamp("window_start"),
    )
    invalid_durations = df_window_sec.filter(col("window_duration_sec") != 300).count()
    if invalid_durations > 0:
        logger.error(f"Detected {invalid_durations} windows that are NOT 5 minutes (300s)!")
        return False
    print("[*] 5-minute tumbling window duration check: PASS (All windows = 300s)")

    # 3. Check window range
    time_summary = df.selectExpr(
        "min(window_start) as earliest_window",
        "max(window_end) as latest_window",
    ).collect()[0]
    print(f"[*] Earliest window: {time_summary['earliest_window']}")
    print(f"[*] Latest window:   {time_summary['latest_window']}")

    # 4. Duplicate feature key check (window_start, zone_id)
    key_dupes = (
        df.groupBy("window_start", "zone_id")
        .count()
        .filter(col("count") > 1)
        .count()
    )
    if key_dupes > 0:
        logger.error(f"Detected {key_dupes} duplicate (window_start, zone_id) keys in {stream_name}!")
        return False
    print("[*] Unique feature key check (window_start, zone_id): PASS (Zero duplicates)")

    # 5. Zone join check: verify zone_name is populated
    unmatched_zones = df.filter(col("zone_name").isNull()).count()
    if unmatched_zones > 0:
        logger.warning(f"Detected {unmatched_zones} rows with unmatched/null zone_name in {stream_name}!")
    else:
        print("[*] Static zone metadata join check: PASS (100% matched zone_name)")

    print(f"\n[PASS] All verification assertions PASSED for {stream_name.upper()}!")
    return True


def main():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    feature_root = os.path.join(repo_root, "data", "feature_table")

    parser = argparse.ArgumentParser(description="Urbanix Feature Table Verification")
    parser.add_argument(
        "--feature-root",
        default=feature_root,
        help="Root directory containing traffic, aqi, and weather feature tables",
    )
    args = parser.parse_args()

    if SparkSession is None:
        logger.error("PySpark is not installed in the active environment. Cannot run verification.")
        sys.exit(1)

    spark = (
        SparkSession.builder.appName("Urbanix-FeatureVerification")
        .config("spark.sql.session.timeZone", "UTC")
        .master("local[2]")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("ERROR")

    datasets = {
        "traffic": os.path.join(args.feature_root, "traffic"),
        "aqi": os.path.join(args.feature_root, "aqi"),
        "weather": os.path.join(args.feature_root, "weather"),
    }

    all_passed = True
    results = {}

    for name, path in datasets.items():
        rules = EXPECTED_SCHEMAS[name]
        passed = verify_dataset(spark, name, path, rules)
        results[name] = passed
        if not passed:
            all_passed = False

    spark.stop()

    print("\n" + "=" * 70)
    print("FINAL VERIFICATION SUMMARY")
    print("=" * 70)
    for name, res in results.items():
        status_str = "PASS" if res else "FAIL"
        print(f"  {name.upper().ljust(10)}: [{status_str}]")

    if all_passed:
        print("\nAll feature tables verified successfully.")
        sys.exit(0)
    else:
        print("\nVerification FAILED on one or more datasets.")
        sys.exit(1)


if __name__ == "__main__":
    main()
